def render_agents_block() -> str:
    """Render the managed AGENTS.md block (markers make the merge idempotent)."""
    from evidencespine.usage import usage_guide_markdown  # lazy

    return AGENTS_MD_BEGIN + "\n" + usage_guide_markdown().strip() + "\n" + AGENTS_MD_END + "\n"


def merge_agents_text(existing: str) -> str:
    """Replace or append the managed block while preserving all user text."""
    text = str(existing or "")
    block = render_agents_block()
    start = text.find(AGENTS_MD_BEGIN)
    end = text.find(AGENTS_MD_END, start + len(AGENTS_MD_BEGIN)) if start >= 0 else -1
    if start >= 0 and end >= 0:
        return text[:start] + block + text[end + len(AGENTS_MD_END) :].lstrip("\n")
    if not text.strip():
        return block
    if not text.endswith("\n"):
        text += "\n"
    return text + "\n" + block


def install_instructions(
    *,
    target_dir: str,
    base_dir: str = ".evidencespine",
    scope: str = "project",
    executable: str = "",
    dry_run: bool = False,
    **_: Any,
) -> Dict[str, Any]:
    """Write/merge the managed AGENTS.md instructions block (never clobbers user text).

    Backs the "instructions" harness target and the --with-agents-md opt-in of
    the lazy harness installers.
    """
    target = os.path.abspath(os.path.expanduser(str(target_dir or ".")))
    path = os.path.join(target, AGENTS_MD_FILENAME)
    existed = os.path.exists(path)
    existing = _read_text(path) or ""
    merged = merge_agents_text(existing)
    changed = (not existed) or merged != existing
    wrote: List[str] = []
    if changed and not dry_run:
        _atomic_write(path, merged)
        wrote.append(path)
    return {
        "status": "ok",
        "harness": "instructions",
        "path": path,
        "scope": str(scope or "project"),
        "wrote": wrote,
        "warnings": [],
        "changed": changed,
        "dry_run": bool(dry_run),
        "base_dir": str(base_dir or ".evidencespine"),
        "executable": str(executable or ""),
        "note": "managed AGENTS.md block merged" if changed else "already current",
    }


def uninstall_instructions(
    *,
    target_dir: str = ".",
    scope: str = "project",
    dry_run: bool = False,
    **_: Any,
) -> Dict[str, Any]:
    """Remove only the managed AGENTS.md block (delete the file when it is all ours)."""
    target = os.path.abspath(os.path.expanduser(str(target_dir or ".")))
    path = os.path.join(target, AGENTS_MD_FILENAME)
    existing = _read_text(path)
    result: Dict[str, Any] = {
        "status": "ok",
        "harness": "instructions",
        "path": path,
        "scope": str(scope or "project"),
        "wrote": [],
        "warnings": [],
        "action": "absent",
        "dry_run": bool(dry_run),
    }
    if existing is None:
        return result
    start = existing.find(AGENTS_MD_BEGIN)
    end = existing.find(AGENTS_MD_END, start + len(AGENTS_MD_BEGIN)) if start >= 0 else -1
    if start < 0 or end < 0:
        return result
    head = existing[:start]
    if head.endswith("\n\n"):
        # Undo the blank separator line appended by merge_agents_text().
        head = head[:-1]
    new_text = head + existing[end + len(AGENTS_MD_END) :].lstrip("\n")
    result["action"] = "removed"
    if dry_run:
        result["content"] = new_text
        return result
    wrote: List[str] = []
    if not new_text.strip():
        try:
            os.unlink(path)
        except OSError:
            pass
    else:
        _atomic_write(path, new_text)
    wrote.append(path)
    result["wrote"] = wrote
    result["removed"] = wrote
    return result

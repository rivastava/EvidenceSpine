"""Skill delivery for DeepSeek Harness and the cross-tool `.agents/skills` root.

DSH discovers skills from `.dsh/skills` (rank 100) and `.agents/skills` (rank
200); Cursor and Cline read `.agents/skills`, so one canonical markdown file
plus per-root materialization covers all three without duplicating content.

The canonical source lives at `skills/evidencespine/SKILL.md` in the repo and is
also rendered on demand from the canonical usage guide
(`evidencespine.usage.usage_guide_markdown()`, imported lazily) so installed
packages without the repo tree still deliver a valid skill.

Frontmatter follows the DSH contract (name + description required; whenToUse and
user-invocable optional). Materialization prefers a *relative symlink* to the
canonical file and falls back to a copy carrying a generated-file marker when
symlinks are unavailable; user-modified copies are never clobbered.
"""

from __future__ import annotations

import os
import tempfile
from typing import Any, Dict, List, Optional

SKILL_NAME = "evidencespine"
#: Canonical source path (repo-relative, POSIX separators by contract).
SKILL_REL_PATH = "skills/evidencespine/SKILL.md"
GENERATED_MARKER = (
    "<!-- generated by evidencespine harness install (skills); "
    "canonical source: skills/evidencespine/SKILL.md -->"
)
SKILL_SOURCE_ENV = "EVIDENCESPINE_SKILL_SOURCE"
AGENTS_MD_FILENAME = "AGENTS.md"
AGENTS_MD_BEGIN = "<!-- evidencespine:begin -->"
AGENTS_MD_END = "<!-- evidencespine:end -->"

#: harness name -> project-scope skill root (relative to target_dir).
_HARNESS_ROOTS: Dict[str, str] = {
    "dsh": os.path.join(".dsh", "skills"),
    "generic": os.path.join(".agents", "skills"),
    "agents": os.path.join(".agents", "skills"),
    "cursor": os.path.join(".agents", "skills"),
    "cline": os.path.join(".agents", "skills"),
}


def render_skill_markdown() -> str:
    """Render the canonical SKILL.md (YAML frontmatter + usage-guide body)."""
    from evidencespine.usage import usage_guide_markdown  # lazy: keeps this module import-light

    body = usage_guide_markdown().strip("\n")
    frontmatter = [
        "---",
        "name: " + SKILL_NAME,
        "description: Evidence-bound memory side-car for project state, grounding, drift checks and handoffs.",
        "whenToUse: Before claiming something is verified, fixed, or shipped, or when importing or "
        "emitting a handoff packet.",
        "user-invocable: true",
        "---",
        "",
    ]
    return "\n".join(frontmatter) + body + "\n"


def canonical_skill_path(target_dir: str = "") -> str:
    """Locate the canonical SKILL.md: env override, project tree, then repo tree."""
    override = str(os.environ.get(SKILL_SOURCE_ENV, "") or "").strip()
    if override:
        candidate = os.path.abspath(os.path.expanduser(override))
        return candidate if os.path.isfile(candidate) else ""
    if str(target_dir or "").strip():
        local = os.path.join(os.path.abspath(os.path.expanduser(str(target_dir))), SKILL_REL_PATH)
        if os.path.isfile(local):
            return os.path.realpath(local)
    module_dir = os.path.dirname(os.path.abspath(__file__))
    # src/evidencespine/harness/skills.py -> repo root is three levels up from harness/.
    repo_root = os.path.abspath(os.path.join(module_dir, os.pardir, os.pardir, os.pardir))
    shipped = os.path.join(repo_root, SKILL_REL_PATH)
    if os.path.isfile(shipped):
        return os.path.realpath(shipped)
    return ""


def _read_text(path: str) -> Optional[str]:
    try:
        with open(path, "r", encoding="utf-8", newline="") as handle:
            return handle.read()
    except (OSError, UnicodeDecodeError):
        return None


def _atomic_write(path: str, text: str) -> None:
    directory = os.path.dirname(os.path.abspath(path)) or "."
    os.makedirs(directory, exist_ok=True)
    mode = 0o644
    try:
        mode = os.stat(path).st_mode & 0o777
    except OSError:
        pass
    fd, tmp = tempfile.mkstemp(prefix=".evidencespine-", suffix=".tmp", dir=directory)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _copy_content() -> str:
    return render_skill_markdown().rstrip("\n") + "\n\n" + GENERATED_MARKER + "\n"


def _materialize_one(
    path: str,
    *,
    source: str,
    content: str,
    warnings: List[str],
    dry_run: bool = False,
) -> str:
    """Create/update one skill copy or symlink; returns added|updated|unchanged|preserved."""
    parent = os.path.dirname(path)
    if not os.path.isdir(parent) and not dry_run:
        os.makedirs(parent, exist_ok=True)
    if source and os.path.realpath(path) == os.path.realpath(source):
        return "unchanged"
    expected_link = os.path.relpath(source, parent) if source else ""
    if os.path.islink(path):
        current = ""
        try:
            current = os.readlink(path)
        except OSError:
            current = ""
        if expected_link and current == expected_link:
            return "unchanged"
        if source and os.path.exists(path) and os.path.realpath(path) == os.path.realpath(source):
            return "unchanged"
        warnings.append(
            path + ": preserved existing symlink -> " + (current or "<unreadable>") + " (not managed by EvidenceSpine)"
        )
        return "preserved"
    if os.path.exists(path):
        current_text = _read_text(path)
        if current_text == content:
            return "unchanged"
        if current_text is not None and GENERATED_MARKER in current_text:
            if not dry_run:
                _atomic_write(path, content)
            return "updated"
        warnings.append(path + ": preserved user-modified skill copy (remove it to let EvidenceSpine manage it)")
        return "preserved"
    if source:
        if dry_run:
            return "added"
        try:
            os.symlink(expected_link, path)
            return "added"
        except (OSError, NotImplementedError) as exc:
            warnings.append(path + ": symlink unavailable (" + str(exc) + "); wrote a copy instead")
    if not dry_run:
        _atomic_write(path, content)
    return "added"


def _normalize_harnesses(harnesses: Any, warnings: List[str]) -> List[str]:
    if isinstance(harnesses, str):
        items = [part.strip() for part in harnesses.split(",") if part.strip()]
    elif isinstance(harnesses, (list, tuple, set)):
        items = [str(part).strip() for part in harnesses if str(part).strip()]
    else:
        items = []
    normalized: List[str] = []
    for item in items:
        name = item.lower()
        if name in {"all", "both", "dsh+generic"}:
            for expanded in ("dsh", "generic"):
                if expanded not in normalized:
                    normalized.append(expanded)
            continue
        if name not in _HARNESS_ROOTS:
            warnings.append("no skill root for harness " + repr(item) + "; skipped")
            continue
        if name not in normalized:
            normalized.append(name)
    return normalized


def materialize(
    *,
    target_dir: str,
    harnesses: List[str],
    executable: str = "",
    scope: str = "project",
    dry_run: bool = False,
) -> Dict[str, Any]:
    """Write or symlink the EvidenceSpine skill into each requested harness root."""
    target = os.path.abspath(os.path.expanduser(str(target_dir or ".")))
    scope_name = "global" if str(scope or "project").strip().lower() in {"global", "user"} else "project"
    warnings: List[str] = []
    requested = _normalize_harnesses(harnesses, warnings)
    source = canonical_skill_path(target)
    content = _read_text(source) if source else None
    if content is None:
        source = ""
        content = _copy_content()
    mode = "symlink" if source else "copy"

    targets: Dict[str, str] = {}
    for harness in requested:
        root = _HARNESS_ROOTS[harness]
        if scope_name == "global":
            rel = SKILL_REL_PATH
        else:
            rel = os.path.join(root, SKILL_NAME, "SKILL.md")
        path = os.path.join(target, rel)
        if path not in targets:
            targets[path] = harness

    wrote: List[str] = []
    planned: List[str] = []
    statuses: Dict[str, str] = {}
    for path, _harness in targets.items():
        status = _materialize_one(path, source=source, content=content, warnings=warnings, dry_run=dry_run)
        statuses[path] = status
        if status in {"added", "updated"}:
            planned.append(path)
            if not dry_run:
                wrote.append(path)
        if status == "added" and not source:
            mode = "copy"

    first = next(iter(statuses), "")
    return {
        "status": "ok",
        "harness": "skills",
        "path": first,
        "scope": scope_name,
        "wrote": wrote,
        "warnings": warnings,
        "targets": statuses,
        "planned": planned,
        "mode": mode,
        "source": source,
        "canonical": source,
        "executable": str(executable or ""),
        "dry_run": bool(dry_run),
    }


